/** 供日志页"停留最久的一段"取文用：讨论帖的 id -> 它的正文首段。 */
export function talkPostText(id: string): string {
  for (const thread of Object.values(TALKS)) {
    for (const post of thread.posts) {
      if (post.id === id) return post.text.split('\n')[0] ?? post.text;
    }
  }
  return '';
}