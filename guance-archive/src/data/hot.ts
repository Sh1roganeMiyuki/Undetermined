export const HOT_SNAPSHOTS: HotSnapshot[] = [hot1031, hot1106, hot1112];

export const HOT_IDS = HOT_SNAPSHOTS.map((s) => s.id);

export function getHotSnapshot(id: string): HotSnapshot | undefined {
  return HOT_SNAPSHOTS.find((s) => s.id === id);
}

/** 话题页的路由穷举：全部上榜话题的 id。 */
export const HOT_TOPIC_IDS = HOT_SNAPSHOTS.flatMap((s) => s.topics.map((t) => t.id));

/** 由话题 id 取话题与其所属快照（话题页用）。 */
export function getHotTopic(id: string): { topic: HotTopic; snapshot: HotSnapshot } | undefined {
  for (const s of HOT_SNAPSHOTS) {
    const t = s.topics.find((x) => x.id === id);
    if (t) return { topic: t, snapshot: s };
  }
  return undefined;
}

/** 供块取文链使用：热榜条目 id -> 文本（渠道名 + 话题词）。 */
export function hotBlockText(id: string): string {
  for (const s of HOT_SNAPSHOTS) {
    for (const t of s.topics) {
      if (t.id === id) return `${s.label} 同城榜 第 ${t.rank} 位：${t.topic}`;
    }
  }
  return '';
}