export const STORIES: Story[] = [story01, story02, story03, story04, story05, story06, story07];

export const STORY_IDS = STORIES.map((s) => s.id);

export function getStory(id: string): Story | undefined {
  return STORIES.find((s) => s.id === id);
}

/** 供日志页取文用：口述块的 id -> 文本。 */
export function storyBlockText(id: string): string {
  for (const story of STORIES) {
    for (const b of story.blocks) {
      if (b.id === id) return b.text ?? b.alt ?? '';
    }
  }
  return '';
}