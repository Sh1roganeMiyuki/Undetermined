/* ------------------------------------------------------------------ *
 * 重复条目：两条同名、同链接、内容互斥的记录。
 *
 * 站内表现为：检索命中某个对象时，给出两条"同名同链接"的结果，
 * 内部编号不同，因此系统不认为这是重复（登记编号不同即为两条记录）。
 * 玩家点进任意一条之后，另一条不再出现——但系统不认为发生过删除，
 * 因此站内没有任何可查的删除痕迹，玩家想找回它只能清档。
 *
 * 影子记录的摘要不进入检索索引：它们只作为命中主记录后的显示变体，
 * 不参与独立匹配，避免"消失"的记录借摘要独有词复现。
 * ------------------------------------------------------------------ */

/** 影子记录文本。RESERVED_NUMBERS 的校验只管词条变体，这里是索引层文本，另行守住不含独占值。 */
export interface DupRecord {
  /** 登记编号，两条不同 */
  id: string;
  meta: string;
  summary: string;
}

export interface DupSet {
  /** 绑定到的主对象 slug */
  group: string;
  records: DupRecord[];
}

