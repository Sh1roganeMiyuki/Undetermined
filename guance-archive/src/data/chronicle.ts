export const CHRONICLES: Story[] = [chronicle01, chronicle02, chronicle03, chronicle04, chronicle05, chronicle06, chronicle07, chronicle08, chronicle09, chronicle10];

export const CHRONICLE_IDS = CHRONICLES.map((s) => s.id);

export function getChronicle(id: string): Story | undefined {
  return CHRONICLES.find((s) => s.id === id);
}

/** 供日志页取文用：纪事块的 id -> 文本。 */
export function chronicleBlockText(id: string): string {
  for (const story of CHRONICLES) {
    for (const b of story.blocks) {
      if (b.id === id) return b.text ?? b.alt ?? '';
    }
  }
  return '';
}