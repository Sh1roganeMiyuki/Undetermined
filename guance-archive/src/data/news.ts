export const NEWS_ISSUES: NewsIssue[] = [news1024, news1104, news1110];

export const NEWS_IDS = NEWS_ISSUES.map((n) => n.id);

export function getNewsIssue(id: string): NewsIssue | undefined {
  return NEWS_ISSUES.find((n) => n.id === id);
}

/** 供块取文链使用：新闻条目 id -> 文本。 */
export function newsBlockText(id: string): string {
  for (const issue of NEWS_ISSUES) {
    for (const item of issue.items) {
      if (item.id === id) return item.text ?? '';
    }
  }
  return '';
}