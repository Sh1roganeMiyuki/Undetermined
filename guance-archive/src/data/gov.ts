export const GOV_DOCS: GovDoc[] = [planDraft, hearing, impl];

export const GOV_IDS = GOV_DOCS.map((d) => d.id);

export function getGovDoc(id: string): GovDoc | undefined {
  return GOV_DOCS.find((d) => d.id === id);
}

/**
 * 由块 id 取规范版文本。日志页"停留最久的一段"用。
 * 与其它栏目同款：撤稿与拦截都不动这里——玩家的台账不该替他改口。
 */
export function govBlockText(id: string): string {
  for (const d of GOV_DOCS) {
    for (const b of d.blocks) {
      if (b.id === id) return b.text ?? (b.items ?? []).join('；');
    }
  }
  return '';
}